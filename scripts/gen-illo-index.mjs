// Generates the build-time illustration index used by components/illustration/Illo.tsx.
//   node scripts/gen-illo-index.mjs           write components/illustration/illo-data.ts + illo-index.ts
//   node scripts/gen-illo-index.mjs --check   exit 1 if those files are stale (used by tests)
// Official store badges (brands/badge-*) are not inlined; use them via <img>.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'public', 'illustrations');
const outDir = path.join(root, 'components', 'illustration');
const HEADER = '// GENERATED by scripts/gen-illo-index.mjs from public/illustrations. Do not edit.\n';

const walk = (dir) =>
  fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
    : [];

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const reactAttr = (a) => (a === 'class' ? 'className' : /^(aria|data)-/.test(a) ? a : camel(a.replace(':', '-')));

export function parseSvg(src, file = 'svg') {
  const m = src.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!m) throw new Error(`${file}: no root <svg> element`);
  const attrs = {};
  let viewBox = '';
  for (const [, k, v] of m[1].matchAll(/([\w:-]+)="([^"]*)"/g)) {
    if (k === 'viewBox') viewBox = v;
    else if (!/^(xmlns(:\w+)?|width|height|version)$/.test(k)) attrs[reactAttr(k)] = v;
  }
  if (!viewBox) throw new Error(`${file}: missing viewBox`);
  return { viewBox, attrs, body: m[2].trim() };
}

export function generate() {
  const files = walk(srcDir)
    .map((f) => path.relative(srcDir, f).split(path.sep).join('/'))
    .filter((rel) => rel.endsWith('.svg') && !rel.startsWith('brands/badge-'))
    .sort();
  const data = [HEADER, "import type { IlloData } from './types';\n"];
  const index = [HEADER, "import * as d from './illo-data';\n", '\nexport const illos = {'];
  for (const rel of files) {
    // Key is the path below public/illustrations without .svg, e.g. 'scenes/beam'.
    const key = rel.replace(/\.svg$/, '');
    const ident = camel(key.replace(/\//g, '-'));
    const parsed = parseSvg(fs.readFileSync(path.join(srcDir, rel), 'utf8'), `public/illustrations/${rel}`);
    data.push(`\nexport const ${ident}: IlloData = ${JSON.stringify(parsed)};\n`);
    index.push(`\n  '${key}': d.${ident},`);
  }
  index.push(files.length ? '\n} as const;\n' : '} as const;\n', '\nexport type IlloName = keyof typeof illos;\n');
  return { 'illo-data.ts': data.join(''), 'illo-index.ts': index.join('') };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generate();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [name, content] of Object.entries(out)) {
    const p = path.join(outDir, name);
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (cur === content) continue;
    if (check) {
      stale = true;
      console.error(`stale: components/illustration/${name} (run: node scripts/gen-illo-index.mjs)`);
    } else fs.writeFileSync(p, content);
  }
  if (stale) process.exit(1);
  if (!check) console.log(`illustration index: ${Object.keys(out).length} files written`);
}
